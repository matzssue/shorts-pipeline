export interface MockContent {
  config: Config;
  topics: Topic[];
  products: Product[];
  films: FilmFiles[];
  publications: Publication[];
  snapshots: StatsSnapshot[];
  ledger: VoiceLedgerRow[];
}

export function buildContent(): MockContent {
  const films = FILMS.map((plan, i) => buildFilm(plan, i + 1));
  const publications = films.flatMap(publicationsFor);
  const published: Published[] = publications
    .filter((pub) => pub.platform !== "tiktok") // TikTok has no API: rows without stats
    .map((pub) => {
      const film = films.find((f) => pub.file.includes(f.folder))!;
      const seconds = (film.compose?.durationInFrames ?? 0) / FPS;
      const key = `${pub.platform}:${film.folder}`;
      const model = videoModel(key, seconds, { hit: film.plan.hit, platformFactor: pub.platform === "instagram" ? [0.5, 1.2] : [1, 1] });
      return { film, pub, model, seconds };
    });
  const days: string[] = [];
  for (let d = addDays(SEASON.start, 1); d <= SEASON.end; d = addDays(d, 1)) days.push(d);
  return {
    config: CONFIG,
    topics: TOPICS.map((v, i) => topicCard(v, i, addDays(SEASON.start, -2))),
    products: PRODUCTS.map((p) => productCard(p, addDays(SEASON.start, -2))),
    films,
    publications,
    snapshots: days.map((d) => snapshot(d, published)),
    ledger: films.flatMap((f) => f.ledger).map((r) => voiceLedgerRowSchema.parse(r)),
  };
}

const json = (data: unknown) => JSON.stringify(data, null, 2) + "\n";

const csvCell = (v: unknown) => {
  const s = v === undefined ? "" : String(v);
  return /[",\n]/.test(s) ? `"${s.replaceAll('"', '""')}"` : s;
};

function csv<T extends Record<string, unknown>>(columns: readonly string[], rows: T[]): string {
  return [columns.join(","), ...rows.map((r) => columns.map((c) => csvCell(r[c])).join(","))].join("\n") + "\n";
}

/** Writes the mock content directory (deleting what was there). Returns the written paths, relative and sorted. */
export function writeContent(dir: string, content = buildContent()): string[] {
  rmSync(dir, { recursive: true, force: true });
  const written: string[] = [];
  const put = (rel: string, text: string) => {
    const file = path.join(dir, rel);
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, text, "utf8");
    written.push(rel.replaceAll("\\", "/"));
  };
  put("shorts.config.json", json(content.config));
  for (const t of content.topics) put(`topics/${t.id}.json`, json(t));
  for (const p of content.products) put(`products/${p.id}.json`, json(p));
  for (const f of content.films) {
    put(`out/${f.folder}/script.json`, json(f.script));
    if (f.voice) put(`out/${f.folder}/voice/${f.plan.narrator}.json`, json(f.voice));
    if (f.compose) put(`out/${f.folder}/compose-${f.plan.narrator}.json`, json(f.compose));
    if (f.qa) put(`out/${f.folder}/qa-${f.plan.narrator}.json`, json(f.qa));
  }
  put("data/publications.csv", csv(PUBLICATION_COLUMNS, content.publications));
  for (const s of content.snapshots) put(`data/stats/${s.measuredAt.slice(0, 10)}.json`, json(s));
  put("data/voice-ledger.csv", csv(VOICE_LEDGER_COLUMNS, content.ledger));
  return written.sort();
}
