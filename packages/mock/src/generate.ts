/** Planned scene length for a line of narration (about 12.5 characters per second plus a breath). */
const plannedSeconds = (line: string) => Math.min(15, Math.max(2.5, Math.ceil((line.length / 12.5 + 0.8) * 2) / 2));

export function topicScript(v: TopicVocab, i: number, plan: FilmPlan): Script {
  const [f1, f2] = v.facts;
  const quiz = plan.series === 2 && v.quiz;
  const sourceLine = `This comes from ${sourceName(i)}.`;
  const w = new Set(plan.warn ?? []);
  let scenes: Script["scenes"] = [
    { kind: "video", duration_s: plannedSeconds(v.hook), visual: `Close-up that shows: ${v.firstFrame}`, prompt: `Vertical close-up, soft daylight, no people: ${v.firstFrame.toLowerCase()}`, voiceover: v.hook, on_screen_text: v.firstFrame, claims: [] },
    { kind: "video", duration_s: plannedSeconds(f1.line), visual: f1.onScreen, prompt: `Vertical shot, hands only, no faces: ${f1.onScreen.toLowerCase()}`, voiceover: f1.line, on_screen_text: f1.onScreen, overlay: { type: "label", heading: v.label.heading, value: v.label.value }, claims: [{ text: f1.text, source: f1.id }] },
    quiz
      ? { kind: "text", duration_s: plannedSeconds(f2.line) + 1, visual: "Quiz card", prompt: "", voiceover: f2.line, on_screen_text: f2.onScreen, overlay: { type: "quiz", options: quiz.options, countdown: 3, answer: quiz.answer }, claims: [{ text: f2.text, source: f2.id }] }
      : { kind: "image", duration_s: plannedSeconds(f2.line), visual: f2.onScreen, prompt: `Still life, top view, no text: ${f2.onScreen.toLowerCase()}`, voiceover: f2.line, on_screen_text: f2.onScreen, claims: [{ text: f2.text, source: f2.id }] },
    { kind: "text", duration_s: plannedSeconds(sourceLine), visual: "Source card", prompt: "", voiceover: sourceLine, on_screen_text: "", overlay: { type: "source", text: `${sourceName(i)}, example.com` }, claims: [] },
    { kind: "video", duration_s: plannedSeconds(v.question) + 0.5, visual: "Wide shot of a tidy shelf", prompt: "Vertical wide shot of a tidy shelf, slow push-in, no people", voiceover: v.question, on_screen_text: "Tell me below", claims: [] },
  ];
  // Quirks that QA reports as warnings: the text changes before the narration, as in a real edit.
  if (w.has("longFirstFrame")) scenes[0] = { ...scenes[0]!, on_screen_text: `${v.firstFrame} and why it matters at home` };
  if (w.has("exclamations")) scenes = scenes.map((sc, k) => (k === 1 || k === 2 ? { ...sc, voiceover: `${sc.voiceover} Try it!` } : sc));
  if (w.has("noSourceCard")) scenes = scenes.map(({ overlay, ...sc }) => (overlay?.type === "source" ? sc : { ...sc, ...(overlay ? { overlay } : {}) }));
  if (w.has("noQuestion")) scenes[4] = { ...scenes[4]!, voiceover: "That is the whole trick.", on_screen_text: "That is the trick" };
  return scriptSchema.parse({
    input: { kind: "topic", id: v.id },
    format: plan.format,
    series: plan.series,
    angle: v.title,
    hooks: [v.hook],
    scenes,
    caption: `${v.title}. Source: ${sourceName(i)}. ${DISCLOSURE}${w.has("linkInCaption") ? " More: https://example.com/tips" : ""}`,
    hashtags: ["#hometips", `#${v.niche.replaceAll("-", "")}`],
    notes: "",
  });
}

export function productScript(p: ProductVocab, plan: FilmPlan): Script {
  const lines = [`Small things everywhere in your drawer?`, `This is the ${p.name.toLowerCase()}.`, `It is made of ${p.material}, with ${p.features.join(" and ")}.`, "Would you use it?"];
  return scriptSchema.parse({
    input: { kind: "product", id: p.id },
    format: plan.format,
    series: plan.series,
    angle: "problem and solution",
    hooks: [lines[0]],
    scenes: [
      { kind: "video", duration_s: 4, visual: "Messy drawer", prompt: "Vertical shot of a messy drawer, no people", voiceover: lines[0], on_screen_text: "Messy drawer?", claims: [] },
      { kind: "video", duration_s: 5, visual: "Product shot", prompt: "", voiceover: lines[1], on_screen_text: p.name, claims: [] },
      { kind: "video", duration_s: 6, visual: "Product in use", prompt: "", voiceover: lines[2], on_screen_text: p.features.join(" · "), claims: [{ text: p.material, source: "facts.material" }] },
      { kind: "video", duration_s: 4, visual: "Tidy drawer", prompt: "Vertical shot of a tidy drawer", voiceover: lines[3], on_screen_text: "Would you use it?", claims: [] },
    ],
    caption: `${p.name}. ${DISCLOSURE}`,
    hashtags: ["#organisation"],
    notes: "",
  });
}

