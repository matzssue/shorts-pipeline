/** Mock TTS: character timings at a steady pace with pauses after punctuation. */
export function mockVoice(script: Script, narrator: Narrator, key: string): VoiceTimings {
  const r = rng(`voice:${key}`);
  const cps = r.float(11.5, 14.5);
  const vt = buildVoiceText(script, narrator.id);
  const chars: { char: string; start: number; end: number }[] = [];
  let t = 0.05;
  for (const ch of vt.text) {
    const d = 1 / cps;
    chars.push({ char: ch, start: round3(t), end: round3(t + d) });
    t += d;
    if (/[.?!]/.test(ch)) t += r.float(0.25, 0.4);
    else if (ch === ",") t += r.float(0.1, 0.18);
  }
  return voiceTimingsSchema.parse({
    narrator: narrator.id,
    provider: "mock",
    voiceId: narrator.voiceId,
    model: narrator.model,
    hash: voiceHash(vt.text, narrator),
    text: vt.text,
    parts: script.scenes.map((sc) => sceneSpoken(sc, narrator.id)),
    sources: script.scenes.map(() => FULL_RECORDING),
    duration_s: chars.at(-1)?.end ?? 0,
    billed_chars: vt.text.length,
    words: toDisplayWords(script, narrator.id, wordTimings(vt.text, chars)),
    scenes: sceneTimings(script, vt, chars),
  });
}

const round3 = (n: number) => Math.round(n * 1000) / 1000;
const round1 = (n: number) => Math.round(n * 10) / 10;

// ---------- one video ----------

export interface FilmFiles {
  plan: FilmPlan;
  number: number;
  folder: string;
  title: string;
  script: Script;
  voice?: VoiceTimings;
  compose?: ComposeProps;
  qa?: ReturnType<typeof runQa>;
  ledger: VoiceLedgerRow[];
}

export function buildFilm(plan: FilmPlan, number: number): FilmFiles {
  const isTopic = plan.kind === "topic";
  const vocabId = isTopic ? TOPICS[plan.index]!.id : PRODUCTS[plan.index]!.id;
  const folder = `${plan.made}-${vocabId}-${plan.format}`;
  const narrator = NARRATORS[plan.narrator];
  let script = isTopic ? topicScript(TOPICS[plan.index]!, plan.index, plan) : productScript(PRODUCTS[plan.index]!, plan);
  const title = isTopic ? TOPICS[plan.index]!.title : PRODUCTS[plan.index]!.name;
  const out: FilmFiles = { plan, number, folder, title, script, ledger: [] };
  if (plan.stage === "scripted") return out;

  const voice = mockVoice(script, narrator, folder);
  out.voice = voice;
  out.ledger.push({ date: plan.made, film: folder, narrator: narrator.id, model: narrator.model, kind: "full", chars: voice.billed_chars ?? voice.text.length });
  if (plan.takes) {
    // Scene 3 re-recorded twice together with its neighbours; take 2 applied.
    const chars = [1, 2, 3].reduce((s, i) => s + (voice.parts?.[i]?.length ?? 0) + 1, 0);
    out.ledger.push({ date: plan.made, film: folder, narrator: narrator.id, model: narrator.model, kind: "take", scene: 3, chars }, { date: plan.made, film: folder, narrator: narrator.id, model: narrator.model, kind: "take", scene: 3, chars });
    voice.sources = voice.sources?.map((s, i) => (i === 2 ? `voice/takes/${narrator.id}-scene-03/take-2` : s));
  }
  if (plan.cache) {
    out.ledger.push({ date: addDays(plan.made, 1), film: folder, narrator: narrator.id, model: narrator.model, kind: "cache", chars: 0 });
  }
  if (plan.stage === "narrated") return out;

  // Generated clips: about 5 s, a bit longer than the scene; one too short (slowed down) on purpose.
  const clipDurations: Record<string, number> = {};
  script.scenes.forEach((sc, i) => {
    if (sc.kind !== "video") return;
    const planned = Math.max(sc.duration_s, voice.scenes[i]?.voice ? voice.scenes[i]!.voice!.end - voice.scenes[i]!.voice!.start + 1 : 0);
    clipDurations[`scenes/${String(i + 1).padStart(2, "0")}.mp4`] = plan.slowClip && i === 1 ? round1(planned * 0.6) : Math.max(5, round1(planned + 1));
  });
  const topic = isTopic ? topicCard(TOPICS[plan.index]!, plan.index, addDays(plan.made, -1)) : undefined;
  const { props } = buildComposeProps({
    script,
    voice,
    audioSrc: `voice/${narrator.id}.mp3`,
    clipDurations,
    publishDate: new Date(`${plan.publish?.date ?? addDays(plan.made, 1)}T12:00:00Z`),
    series: plan.series,
    seriesTitle: CONFIG.series[String(plan.series)] ?? "",
    sourceLabel: CONFIG.sourceLabel,
  });
  out.compose = composePropsSchema.parse(props);

  if (plan.stage === "qaFailed") {
    // The script was edited after the narration was recorded: QA catches the mismatch.
    const scenes = script.scenes.map((sc, i) => (i === 1 ? { ...sc, voiceover: `${sc.voiceover} It takes a minute.` } : sc));
    script = scriptSchema.parse({ ...script, scenes });
    out.script = script;
  }
  if (topic) {
    out.qa = qaResultSchema.parse(
      runQa({
        script,
        topic,
        format: plan.format,
        narrator,
        voice,
        video: { duration: props.durationInFrames / FPS, width: 1080, height: 1920 },
        mtimes: { script: 1, voice: 2, video: 3 },
        disclosure: DISCLOSURE,
      }),
    );
  }
  return out;
}

// ---------- publications and stats ----------

const pad4 = (n: number) => String(n).padStart(4, "0");

export function publicationsFor(f: FilmFiles): Publication[] {
  if (!f.plan.publish) return [];
  const n = pad4(f.number);
  const links: Record<Platform, string> = {
    youtube: `https://example.com/shorts/mock-yt-${n}`,
    instagram: `https://example.com/reel/mock-ig-${n}/`,
    tiktok: `https://example.com/tiktok/mock-tt-${n}`,
  };
  return f.plan.publish.platforms.map((platform) =>
    publicationSchema.parse({
      date: f.plan.publish!.date,
      platform,
      channel: f.plan.channel,
      file: `out/${f.folder}/final-${f.plan.narrator}.mp4`,
      link: links[platform],
      status: "published",
    }),
  );
}

interface Published {
  film: FilmFiles;
  pub: Publication;
  model: VideoModel;
  seconds: number;
}

export function snapshot(day: string, published: Published[]): StatsSnapshot {
  const noInsights = IG_NO_INSIGHTS_DAYS.includes(day);
  const live = published.filter((p) => p.pub.date < day);
  const ref = (p: Published) => ({ date: p.pub.date, channel: p.pub.channel, link: p.pub.link });

  const youtube = live
    .filter((p) => p.pub.platform === "youtube")
    .map((p) => {
      const days = daysBetween(p.pub.date, day);
      const views = viewsAt(p.model, days);
      const analytics =
        days > ANALYTICS_DELAY_DAYS
          ? { avgViewPercent: p.model.avgViewPercent, avgViewSeconds: Math.round((p.model.avgViewPercent / 100) * p.seconds), shares: share(views, p.model.shareRate), subscribersGained: share(views, p.model.subRate) }
          : {};
      return {
        id: `mock-yt-${pad4(p.film.number)}`,
        title: p.film.title,
        publishedAt: `${p.pub.date}T16:00:00Z`,
        privacy: "public",
        views,
        likes: share(views, p.model.likeRate),
        comments: share(views, p.model.commentRate),
        ...analytics,
        pub: ref(p),
      };
    });

  const instagram = live
    .filter((p) => p.pub.platform === "instagram")
    .map((p) => {
      const views = viewsAt(p.model, daysBetween(p.pub.date, day));
      const insights = noInsights
        ? {}
        : {
            views,
            reach: Math.round(views * 0.74),
            shares: share(views, p.model.shareRate),
            saved: share(views, p.model.shareRate * 1.5),
            totalInteractions: share(views, p.model.likeRate + p.model.commentRate + p.model.shareRate * 2.5),
            avgWatchSeconds: round1((p.model.avgViewPercent / 100) * p.seconds * 0.8),
          };
      return {
        id: `mock-ig-${pad4(p.film.number)}`,
        permalink: p.pub.link,
        timestamp: `${p.pub.date}T16:05:00+0000`,
        likes: share(views, p.model.likeRate),
        comments: share(views, p.model.commentRate),
        ...insights,
        pub: ref(p),
      };
    });

  const accounts = CONFIG.channels.map((ch, ci) => {
    const yt = live.filter((p) => p.pub.channel === ch.id && p.pub.platform === "youtube");
    const ig = live.filter((p) => p.pub.channel === ch.id && p.pub.platform === "instagram");
    const ytViews = yt.map((p) => viewsAt(p.model, daysBetween(p.pub.date, day)));
    const igViews = ig.map((p) => viewsAt(p.model, daysBetween(p.pub.date, day)));
    return {
      channel: ch.id,
      youtube: {
        id: `mock-channel-${ch.id}`,
        title: ch.name,
        subscribers: [31, 18][ci]! + yt.reduce((s, p, i) => s + share(ytViews[i]!, p.model.subRate), 0),
        views: ytViews.reduce((s, v) => s + v, 0),
        videos: yt.length,
      },
      instagram: {
        username: `example_channel_${ch.id}`,
        followers: [44, 27][ci]! + Math.round(igViews.reduce((s, v) => s + v, 0) * 0.004),
        mediaCount: ig.length,
      },
    };
  });

  return statsSnapshotSchema.parse({
    measuredAt: `${day}T${MEASURED_AT_TIME}`,
    accounts,
    youtube,
    instagram,
    notes: noInsights ? ["Instagram insights: missing permission (code 10) – views, reach and watch time not measured."] : [],
  });
}

